// ═══════════════════════════════════════════════════════════════
// VALIDIM I URL
// ═══════════════════════════════════════════════════════════════

export function isValidImageUrl(url: string | null | undefined): boolean {
  if (!url) return false
  if (typeof url !== 'string') return false
  if (!url.startsWith('http')) return false
  if (url.length < 20) return false
  if (!url.includes('unsplash.com')) return false
  return true
}

// ═══════════════════════════════════════════════════════════════
// PICK IMAGES - ME VALIDIM
// ═══════════════════════════════════════════════════════════════

export function pickImages(propertyType: string, count = 4): string[] {
  let pool: string[]

  switch (propertyType) {
    case 'apartment':
      pool = APARTMENT_IMAGES
      break
    case 'house':
      pool = HOUSE_IMAGES
      break
    case 'villa':
      pool = VILLA_IMAGES
      break
    case 'studio':
      pool = STUDIO_IMAGES
      break
    case 'penthouse':
      pool = PENTHOUSE_IMAGES
      break
    case 'commercial':
      pool = COMMERCIAL_IMAGES
      break
    case 'office':
      pool = OFFICE_IMAGES
      break
    default:
      pool = APARTMENT_IMAGES
  }

  const validPool = pool.filter((url) => isValidImageUrl(url))

  if (validPool.length === 0) {
    return [FALLBACK_IMAGE]
  }

  const shuffled = [...validPool].sort(() => Math.random() - 0.5)
  const actualCount = Math.min(count, shuffled.length)
  const selected = shuffled.slice(0, actualCount)

  return selected.length > 0 ? selected : [validPool[0]]
}

// ═══════════════════════════════════════════════════════════════
// GET PRIMARY IMAGE
// ═══════════════════════════════════════════════════════════════

export function getPrimaryImage(
  images: string[] | null | undefined
): string {
  if (!images || images.length === 0) {
    return FALLBACK_IMAGE
  }

  const validImage = images.find((url) => isValidImageUrl(url))

  return validImage || FALLBACK_IMAGE
}